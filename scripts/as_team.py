class Publisher:
    """Puts a local series on GitHub as the team's bot."""

    def __init__(self, github: GitHub, git: Git, guard: MessageGuard) -> None:
        self.github = github
        self.git = git
        self.guard = guard

    def remote_head(self, repo: str, branch: str, token: str) -> str | None:
        """Return the branch's head on GitHub, or None when the branch does not exist."""
        try:
            ref = self.github.call(
                "GET", f"/repos/{repo}/git/ref/heads/{urllib.parse.quote(branch)}", token
            )
        except Refusal as missing:
            if " 404 " in str(missing):
                return None
            raise
        return str(ref["object"]["sha"])

    def remote_tree(self, repo: str, sha: str, token: str) -> str:
        """Return the tree of a commit on GitHub."""
        return str(
            self.github.call("GET", f"/repos/{repo}/git/commits/{sha}", token)["tree"]["sha"]
        )

    def publish_api(self, team: str, repo: str, branch: str, base: str, head: str = "HEAD") -> str:
        """Replay base..head on GitHub with createCommitOnBranch: bot-authored, GitHub-signed commits.

        A new branch starts at `base`, which GitHub must already have. An existing branch takes
        the series only when its tree is exactly the tree of `base`, so nothing on it is lost.
        At the end the branch's tree must equal the local head's tree, byte for byte.

        Args:
            team: The authoring team.
            repo: `owner/name`.
            branch: The branch to create or extend on GitHub.
            base: The local commit the series starts after.
            head: The series' last commit.

        Returns:
            The new head's commit id on GitHub.
        """
        commits = self.git.commits(base, head)
        series = []
        for commit in commits:
            message = self.guard.clean(self.git.run("log", "-1", "--format=%B", commit).decode())
            series.append((commit, message, *self.git.changes(commit)))
        token = self.github.installation_token(team, repo)
        base_sha = self.git.text("rev-parse", f"{base}^{{commit}}")
        expected = self.remote_head(repo, branch, token)
        if expected is None:
            self.github.call(
                "POST",
                f"/repos/{repo}/git/refs",
                token,
                {"ref": f"refs/heads/{branch}", "sha": base_sha},
            )
            expected = base_sha
        elif self.remote_tree(repo, expected, token) != self.git.text(
            "rev-parse", f"{base}^{{tree}}"
        ):
            raise Refusal(
                f"{branch} on GitHub is not at {base}'s tree; fetch it and rebase the series onto it"
            )
        for _commit, message, additions, deletions in series:
            headline, _, body = message.partition("\n")
            change: dict[str, Any] = {
                "branch": {"repositoryNameWithOwner": repo, "branchName": branch},
                "message": {"headline": headline, "body": body.strip("\n")},
                "fileChanges": {"additions": additions, "deletions": deletions},
                "expectedHeadOid": expected,
            }
            data = self.github.graphql(token, CREATE_COMMIT, {"input": change})
            expected = str(data["createCommitOnBranch"]["commit"]["oid"])
        if self.remote_tree(repo, expected, token) != self.git.text(
            "rev-parse", f"{head}^{{tree}}"
        ):
            raise Refusal(
                f"{branch} on GitHub does not match {head}'s tree; nothing was merged, inspect the branch"
            )
        return expected

    def commit(self, team: str, message: str, now: datetime | None = None) -> str:
        """Commit what is staged, as the bot, dated in UTC, with the guarded message.

        Returns:
            The new commit's id.
        """
        cleaned = self.guard.clean(message)
        login, email = self.github.identity(team)
        stamp = (now or datetime.now(UTC)).strftime("%Y-%m-%dT%H:%M:%S+0000")
        identity = {
            "GIT_AUTHOR_NAME": login,
            "GIT_AUTHOR_EMAIL": email,
            "GIT_COMMITTER_NAME": login,
            "GIT_COMMITTER_EMAIL": email,
            "GIT_AUTHOR_DATE": stamp,
            "GIT_COMMITTER_DATE": stamp,
            "TZ": "UTC",
        }
        self.git.run("commit", "--no-verify", "-F", "-", env=identity, stdin=cleaned.encode())
        return self.git.text("rev-parse", "HEAD")

    def publish_git(self, team: str, repo: str, branch: str, base: str, head: str = "HEAD") -> None:
        """Push base..head as it is, after checking every commit is this bot's and its message clean."""
        _login, email = self.github.identity(team)
        for commit in self.git.commits(base, head):
            author, committer = self.git.text("log", "-1", "--format=%ae%n%ce", commit).splitlines()
            if author != email or committer != email:
                raise Refusal(
                    f"{commit[:12]} is not {bot_login(team)}'s; make the series with `as_team.py commit {team}`"
                )
            message = self.git.run("log", "-1", "--format=%B", commit).decode().rstrip("\n")
            if self.guard.clean(message) != message:
                raise Refusal(f"{commit[:12]}'s message carries a line no bot sends; reword it")
        token = self.github.installation_token(team, repo)
        basic = base64.b64encode(f"x-access-token:{token}".encode()).decode()
        # The token goes in through the environment, never the command line other users can list.
        header = {
            "GIT_CONFIG_COUNT": "1",
            "GIT_CONFIG_KEY_0": f"http.{WEB}/.extraheader",
            "GIT_CONFIG_VALUE_0": f"AUTHORIZATION: basic {basic}",
        }
        self.git.run("push", f"{WEB}/{repo}.git", f"{head}:refs/heads/{branch}", env=header)


class PullRequests:
    """Pull requests, reviews, the review gate and merges, each as one team's bot."""

    def __init__(self, github: GitHub, registry: TeamRegistry, guard: MessageGuard) -> None:
        self.github = github
        self.registry = registry
        self.guard = guard

    def open(
        self, team: str, repo: str, branch: str, base: str, title: str, body: str
    ) -> dict[str, Any]:
        """Open a pull request from `branch` as the team's bot and return it."""
        token = self.github.installation_token(team, repo)
        request = {
            "title": self.guard.clean(title),
            "head": branch,
            "base": base,
            "body": self.guard.clean(body),
        }
        return dict(self.github.call("POST", f"/repos/{repo}/pulls", token, request))

    def required(
        self, repo: str, number: int, token: str
    ) -> tuple[dict[str, Any], str | None, set[str]]:
        """Return the pull request, its author's team and the teams that must approve it."""
        pull = self.github.call("GET", f"/repos/{repo}/pulls/{number}", token)
        files = self.github.pages(f"/repos/{repo}/pulls/{number}/files", token)
        author = self.registry.team_of_login(pull["user"]["login"])
        paths = [item["filename"] for item in files] + [
            item["previous_filename"] for item in files if item.get("previous_filename")
        ]
        return pull, author, self.registry.required_reviewers(author, paths)

    def review(self, team: str, repo: str, number: int, event: str, body: str) -> dict[str, Any]:
        """Submit a review as the team's bot on the pull request's current head.

        A team never reviews its own pull request (GitHub would not count it either).
        """
        token = self.github.installation_token(team, repo)
        pull, author, required = self.required(repo, number, token)
        if author == team:
            raise Refusal(
                f"#{number} is {bot_login(team)}'s own pull request; another team reviews it"
            )
        if team not in required:
            print(
                f"💡 {team} is not among the teams this change needs ({', '.join(sorted(required))})"
            )
        review: dict[str, Any] = {"commit_id": pull["head"]["sha"], "event": event}
        cleaned = self.guard.clean(body)
        if cleaned or event != "APPROVE":
            review["body"] = cleaned
        return dict(
            self.github.call("POST", f"/repos/{repo}/pulls/{number}/reviews", token, review)
        )

    def gate(self, repo: str, number: int) -> tuple[str, str]:
        """Set the `team-review` status on the head, as the Quality bot.

        Success needs, for every required team, that team's bot's latest review to be an approval
        of the current head, and no team's latest review to request changes.

        Returns:
            The state set and its description.
        """
        token = self.github.installation_token(GATE_TEAM, repo)
        pull, _author, required = self.required(repo, number, token)
        head = pull["head"]["sha"]
        latest: dict[str, dict[str, Any]] = {}
        for review in self.github.pages(f"/repos/{repo}/pulls/{number}/reviews", token):
            team = self.registry.team_of_login(review["user"]["login"])
            if team and review["state"] in ("APPROVED", "CHANGES_REQUESTED", "DISMISSED"):
                latest[team] = review
        blocking = sorted(
            team for team, review in latest.items() if review["state"] == "CHANGES_REQUESTED"
        )
        approved = {
            team
            for team, review in latest.items()
            if review["state"] == "APPROVED" and review["commit_id"] == head
        }
        missing = sorted(required - approved)
        if blocking:
            state, description = "failure", f"changes requested by: {', '.join(blocking)}"
        elif missing:
            state, description = "pending", f"waiting for: {', '.join(missing)}"
        else:
            state, description = "success", f"approved by: {', '.join(sorted(required))}"
        status = {"state": state, "context": GATE_CONTEXT, "description": description[:140]}
        self.github.call("POST", f"/repos/{repo}/statuses/{head}", token, status)
        return state, description

    def merge(self, team: str, repo: str, number: int) -> dict[str, Any]:
        """Squash-merge the pull request as the team's bot, with its guarded title and body."""
        token = self.github.installation_token(team, repo)
        pull = self.github.call("GET", f"/repos/{repo}/pulls/{number}", token)
        request = {
            "merge_method": "squash",
            "sha": pull["head"]["sha"],
            "commit_title": f"{self.guard.clean(pull['title'])} (#{number})",
            "commit_message": self.guard.clean(pull.get("body") or ""),
        }
        return dict(self.github.call("PUT", f"/repos/{repo}/pulls/{number}/merge", token, request))


class ManifestRegistration:
    """GitHub's App-manifest flow: the form that posts a manifest, and the code's exchange."""

    def __init__(self, github: GitHub, registry: TeamRegistry) -> None:
        self.github = github
        self.registry = registry

    def form(self, team: str, redirect_url: str, state: str) -> str:
        """Return the form whose one button posts the team's manifest to the organisation."""
        manifest = {**self.registry.manifest(team), "redirect_url": redirect_url}
        query = urllib.parse.urlencode({"state": state})
        action = f"{WEB}/organizations/{self.registry.org}/settings/apps/new?{query}"
        return (
            f'<form action="{html.escape(action)}" method="post">'
            f'<input type="hidden" name="manifest" value="{html.escape(json.dumps(manifest))}">'
            f'<button type="submit">Create {html.escape(manifest["name"])}</button></form>'
        )

    def convert(self, team: str, code: str, directory: Path | None = None) -> AppCredentials:
        """Exchange the flow's code for the App's id, slug and key, and store them."""
        conversion = self.github.call(
            "POST", f"/app-manifests/{urllib.parse.quote(code)}/conversions"
        )
        expected = self.registry.manifest(team)["name"]
        if conversion.get("slug") != expected:
            print(
                f"⚠️ GitHub named the App '{conversion.get('slug')}', not '{expected}'; "
                "the bot's login follows the slug"
            )
        return AppCredentials.store(team, conversion, directory)


