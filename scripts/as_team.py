@dataclass
class Run:
    """What one command needs: its arguments and the objects it acts through."""

    args: argparse.Namespace
    registry: TeamRegistry
    github: GitHub
    guard: MessageGuard
    git: Git
    clock: Callable[[], datetime] = field(default=lambda: datetime.now(UTC))

    @property
    def team(self) -> str:
        """Return the command's team, checked against the registry."""
        return self.registry.check(self.args.team)

    def body(self) -> str:
        """Return the body file's text, or an empty body."""
        path: Path | None = self.args.body_file
        return path.read_text() if path else ""

    def pulls(self) -> PullRequests:
        """Return the pull-request actions for this run."""
        return PullRequests(self.github, self.registry, self.guard)

    def publisher(self) -> Publisher:
        """Return the publisher for this run."""
        return Publisher(self.github, self.git, self.guard)

    def in_hours(self) -> bool:
        """Return whether now (UTC) is one of the publishing hours."""
        return self.clock().hour in self.registry.publish_hours

    def writes(self) -> None:
        """Refuse a write to GitHub outside the publishing hours, unless --now."""
        if not self.args.now and not self.in_hours():
            hours = ", ".join(f"{hour:02d}:00" for hour in self.registry.publish_hours)
            raise Refusal(
                f"GitHub is written only at {hours} UTC: hold it with `as_team.py queue "
                f"{self.args.command} …` (or pass --now)"
            )


class PublishQueue:
    """Commands held for the next publishing hour, one JSON file each, run oldest first."""

    def __init__(self, folder: Path | None = None) -> None:
        self.folder = folder or key_dir() / "queue"

    def entries(self) -> list[Path]:
        """Return the held commands' files, oldest first."""
        return sorted(self.folder.glob("*.json")) if self.folder.is_dir() else []

    def hold(self, argv: list[str], cwd: Path, git: Git, now: datetime) -> Path:
        """Hold a command, pinned so that it does at flush time what it would do now.

        `publish`'s `--base` and `--head` become commit ids, and a `--body-file` is copied in,
        because the worktree and the file may have moved on by the publishing hour.

        Returns:
            The held command's file.
        """
        args = parser().parse_args(argv)
        if args.command not in HELD_COMMANDS:
            raise Refusal(f"only {', '.join(HELD_COMMANDS)} are held; run {args.command} directly")
        pinned = list(argv)
        self.folder.mkdir(parents=True, exist_ok=True, mode=0o700)
        stamp = now.strftime("%Y%m%dT%H%M%S")
        name = f"{stamp}-{len(self.entries()):04d}"
        if args.command == "publish":
            pinned += ["--base", git.text("rev-parse", f"{args.base}^{{commit}}")]
            pinned += ["--head", git.text("rev-parse", f"{args.head}^{{commit}}")]
        if getattr(args, "body_file", None):
            copy = self.folder / f"{name}.body"
            copy.write_text(args.body_file.read_text())
            pinned += ["--body-file", str(copy)]
        entry = self.folder / f"{name}.json"
        entry.write_text(json.dumps({"argv": pinned, "cwd": str(cwd)}, indent=2) + "\n")
        return entry


HELD_COMMANDS: Final[tuple[str, ...]] = ("publish", "pr", "review", "gate", "merge")


def run_status(run: Run) -> None:
    """Print, for each team, whether its App's key is on this machine."""
    for team in run.registry.teams:
        try:
            credentials = AppCredentials.load(team)
            print(f"✅ {team:12} app {credentials.app_id} ({credentials.slug})")
        except Refusal as missing:
            print(f"❌ {team:12} {missing}")


def run_owners(run: Run) -> None:
    """Print each path's owning teams, or with --author the teams that must review."""
    if run.args.author:
        author = run.registry.check(run.args.author)
        print(" ".join(sorted(run.registry.required_reviewers(author, run.args.paths))))
        return
    for path in run.args.paths:
        print(f"{path}: {' '.join(sorted(run.registry.owning_teams(path))) or '-'}")


def run_register(run: Run) -> None:
    """Serve the phone's page for the listed teams (default: every team without an App)."""
    teams = [run.registry.check(team) for team in run.args.teams] or list(run.registry.teams)
    address = run.args.address or lan_address()
    hostname = socket.gethostname().split(".")[0]
    registration = ManifestRegistration(run.github, run.registry)

    def site_for(port: int) -> RegistrationSite:
        names = [f"{hostname}.local:{port}", f"{address}:{port}"]
        return RegistrationSite(registration, teams, names, secrets.token_urlsafe(18))

    pending = [
        team for team in teams if team not in RegistrationSite(registration, teams, [], "").done
    ]
    if not pending:
        print("✅ every listed team has its App")
        return
    site = serve_registration(site_for, address)
    for team in teams:
        mark = f"✅ app {site.done[team].app_id}" if team in site.done else "❌ not registered"
        print(f"{team:12} {mark}")


def run_whoami(run: Run) -> None:
    """Print the bot's login and commit email."""
    login, email = run.github.identity(run.team)
    print(f"{login} <{email}>")


def run_commit(run: Run) -> None:
    """Commit what is staged, as the bot."""
    print(f"✅ {run.publisher().commit(run.team, run.args.message)}")


def run_publish(run: Run) -> None:
    """Put base..head on a GitHub branch as the bot, through the API or a push."""
    run.writes()
    args = run.args
    branch = run.guard.name(args.branch)
    if args.via == VIA_GIT:
        run.publisher().publish_git(run.team, args.repo, branch, args.base, args.head)
        print(f"✅ pushed {args.base}..{args.head} to {branch} as {bot_login(run.team)}")
        return
    head = run.publisher().publish_api(run.team, args.repo, branch, args.base, args.head)
    print(f"✅ {branch} is at {head} on GitHub; the local commits stay as they were")


def run_pr(run: Run) -> None:
    """Open a pull request as the bot."""
    run.writes()
    args = run.args
    branch = run.guard.name(args.branch)
    opened = run.pulls().open(run.team, args.repo, branch, args.base, args.title, run.body())
    print(f"✅ #{opened['number']} {opened['html_url']}")


def run_review(run: Run) -> None:
    """Review a pull request as the bot."""
    run.writes()
    args = run.args
    submitted = run.pulls().review(run.team, args.repo, args.number, args.event, run.body())
    print(f"✅ {submitted['state']} by {bot_login(run.team)}")


def run_gate(run: Run) -> None:
    """Set the team-review status as the Quality bot."""
    run.writes()
    state, description = run.pulls().gate(run.args.repo, run.args.number)
    mark = "✅" if state == GATE_SUCCESS else "⚠️"
    print(f"{mark} {GATE_CONTEXT}: {state}, {description}")


def run_merge(run: Run) -> None:
    """Squash-merge as the bot. Only when the owner has said so for this pull request."""
    run.writes()
    merged = run.pulls().merge(run.team, run.args.repo, run.args.number)
    print(f"✅ merged as {merged.get('sha', '')}")


def run_queue(run: Run) -> None:
    """Hold a command for the next publishing hour, or list what is held."""
    queue = PublishQueue()
    if not run.args.held:
        for entry in queue.entries():
            print(f"{entry.stem}  {' '.join(json.loads(entry.read_text())['argv'])}")
        return
    held = [*([] if run.args.repo == DEFAULT_REPO else ["--repo", run.args.repo]), *run.args.held]
    entry = queue.hold(held, run.git.cwd, run.git, run.clock())
    print(f"✅ held as {entry.stem}; it runs at the next publishing hour")


def run_flush(run: Run) -> None:
    """Run the held commands in order, if this is a publishing hour (or --now).

    The first one that fails stops the flush: later ones may depend on it (a pull request on
    the branch a held publish creates). It and everything after it stay held.
    """
    if not run.args.now and not run.in_hours():
        return
    queue = PublishQueue()
    for entry in queue.entries():
        held = json.loads(entry.read_text())
        args = parser().parse_args(["--now", *held["argv"]])
        step = Run(args, run.registry, run.github, run.guard, Git(Path(held["cwd"])), run.clock)
        try:
            COMMANDS[args.command](step)
        except Refusal as refused:
            raise Refusal(f"{entry.stem} stopped the flush: {refused}") from refused
        entry.unlink()
        body = entry.with_suffix(".body")
        if body.exists():
            body.unlink()


def run_timer(run: Run) -> None:
    """Print the systemd user units that run `flush` a few minutes into each publishing hour."""
    hours = ",".join(f"{hour:02d}" for hour in run.registry.publish_hours)
    print(
        "# ~/.config/systemd/user/team-bots-flush.service\n"
        "[Unit]\nDescription=Publish the team bots' held commands\n\n"
        "[Service]\nType=oneshot\nEnvironment=TZ=UTC\n"
        f"WorkingDirectory={REPO_ROOT}\n"
        f"ExecStart={sys.executable} {Path(__file__).resolve()} flush\n\n"
        "# ~/.config/systemd/user/team-bots-flush.timer\n"
        "[Unit]\nDescription=The team bots' publishing hours\n\n"
        f"[Timer]\nOnCalendar=*-*-* {hours}:05:00 UTC\nPersistent=false\n\n"
        "[Install]\nWantedBy=timers.target"
    )


def run_check_message(run: Run) -> None:
    """Print a message as the bots would send it."""
    path: Path | None = run.args.file
    print(run.guard.clean(path.read_text() if path else sys.stdin.read()))


COMMANDS: Final[dict[str, Callable[[Run], None]]] = {
    "status": run_status,
    "owners": run_owners,
    "register": run_register,
    "whoami": run_whoami,
    "commit": run_commit,
    "publish": run_publish,
    "pr": run_pr,
    "review": run_review,
    "gate": run_gate,
    "merge": run_merge,
    "queue": run_queue,
    "flush": run_flush,
    "timer": run_timer,
    "check-message": run_check_message,
}


def main(
    argv: Sequence[str] | None = None,
    github: GitHub | None = None,
    cwd: Path | None = None,
    clock: Callable[[], datetime] | None = None,
) -> int:
    """Run one command; 0 on success, 1 when refused.

    Args:
        argv: The arguments (default: the command line).
        github: The API client (tests pass one with a fake session).
        cwd: The repository to read commits from (default: the current folder).
        clock: The current time, in UTC (tests pass a fixed one).

    Returns:
        The exit status.
    """
    args = parser().parse_args(argv)
    run = Run(args, TeamRegistry(), github or GitHub(), MessageGuard(), Git(cwd or Path.cwd()))
    if clock:
        run.clock = clock
    try:
        COMMANDS[args.command](run)
    except Refusal as refused:
        print(f"❌ {refused}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
