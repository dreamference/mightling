"""Act on GitHub as one of Dreamference's team bots: commits, pull requests, reviews, the review gate.

specs/DREAMFERENCE_ORGANISATION.md §5 and §6. Each of the fifteen teams in `.github/apps/teams.json`
has a GitHub App, `dreamference-<team>`, registered from `.github/apps/<team>.json` under the
`dreamference` organisation. GitHub shows what the App does as `dreamference-<team>[bot]`, with a
"bot" badge. This script is the only way the agents act as a team, so every message passes the
same guard before it leaves the machine.

    status                                     which teams have credentials here (no network)
    owners <path>... [--author TEAM]           the teams that own (or must review) these paths
    register [TEAM...]                         the phone's page on the LAN that registers the Apps
    whoami <team>                              the bot's login and the commit email GitHub links
    commit <team> -m MSG                       a local commit as the bot, dated in UTC
    publish <team> --branch B [--base REF]     replays REF..HEAD as GitHub-signed bot commits
    publish <team> --branch B --via git        pushes REF..HEAD (made by `commit`) as they are
    pr <team> --branch B --title T [--body-file F]   opens a pull request as the bot
    review <team> <number> --approve|--request-changes|--comment [--body-file F]
    gate <number>                              sets the `team-review` status, as the Quality bot
    merge <team> <number>                      merges (squash) as the bot, when the owner says
    queue [COMMAND ...]                        holds a write for the next publishing hour (or lists)
    flush                                      runs what is held, if this is a publishing hour
    timer                                      prints the systemd user units that run flush
    check-message [FILE]                       prints the message as the bots would send it

GitHub is written only at the publishing hours (`publish_hours_utc` in teams.json, 09:00 and 21:00
UTC); outside them a write is refused unless held with `queue` or forced with `--now`.

The guard (`MessageGuard`) strips every co-author and session trailer and every line that starts
"Generated with" or "Generated by" (saying on stderr what it stripped), then refuses any text or
branch name matching an entry of two lists kept outside the repository, so that it never names
what it forbids: `~/.config/dreamference/team-bots/denylist.txt` and
`~/.config/dreamference/anonymity-denylist.txt`. Without either the script sends nothing.

Keys never enter the repository: `register` (the page on the LAN, only while it runs, under a
random path token) writes `<team>.pem` (0600) and `<team>.json` (the App's
id and slug) into `~/.config/dreamference/team-bots/` (0700), and every other command refuses a key
or a folder anyone else can read. Installation tokens live for an hour; they are minted per run,
kept in memory and never printed. The App's JSON web token is signed with `openssl`, so the script
needs nothing beyond the package's own dependencies.
"""

