class Refusal(Exception):
    """A reason to stop before anything is sent; printed as is."""


def key_dir() -> Path:
    """Return the folder holding the Apps' keys, the App ids and the denylist."""
    configured = os.environ.get(KEY_DIR_ENV)
    if configured:
        return Path(configured)
    return Path.home() / ".config" / "dreamference" / "team-bots"


def bot_login(team: str) -> str:
    """Return the login GitHub gives a team's App: `dreamference-<team>[bot]`."""
    return f"{BOT_PREFIX}{team}[bot]"


class CodeOwners:
    """GitHub's CODEOWNERS rules: gitignore-style patterns, the last matching line wins."""

    def __init__(self, rules: list[tuple[str, tuple[str, ...]]]) -> None:
        self.rules = rules

    @classmethod
    def parse(cls, text: str) -> "CodeOwners":
        """Read CODEOWNERS text into (pattern, owners) rules, comments and blanks dropped.

        Args:
            text: The file's contents.

        Returns:
            The rules in file order.
        """
        rules: list[tuple[str, tuple[str, ...]]] = []
        for raw in text.splitlines():
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            pattern, *owners = line.split()
            rules.append((pattern, tuple(owners)))
        return cls(rules)

    @staticmethod
    def matches(pattern: str, path: str) -> bool:
        """Return whether a CODEOWNERS pattern covers a repository path.

        Args:
            pattern: A CODEOWNERS pattern (`*`, `/dir/`, `/file`, `/dir/name_*`).
            path: A path relative to the repository root, `/`-separated.

        Returns:
            True when the pattern names the path or a folder that holds it.
        """
        if pattern == "*":
            return True
        anchored = pattern.startswith("/") or "/" in pattern.rstrip("/")
        body = pattern.lstrip("/")
        if body.endswith("/"):
            if anchored:
                return path.startswith(body)
            return f"/{body}" in f"/{path}"
        regex = ""
        index = 0
        while index < len(body):
            if body.startswith("**", index):
                regex += ".*"
                index += 2
                continue
            char = body[index]
            regex += "[^/]*" if char == "*" else "[^/]" if char == "?" else re.escape(char)
            index += 1
        full = rf"{regex}(/.*)?"
        if anchored:
            return re.fullmatch(full, path) is not None
        return re.fullmatch(rf"(.*/)?{full}", path) is not None

    def owners(self, path: str) -> tuple[str, ...]:
        """Return the owners of the last rule that matches the path (empty when none does)."""
        found: tuple[str, ...] = ()
        for pattern, owners in self.rules:
            if self.matches(pattern, path):
                found = owners
        return found


class TeamRegistry:
    """The fifteen teams: `.github/apps/teams.json`, the manifests and the code owners."""

    def __init__(self, apps_dir: Path = APPS_DIR, repo_root: Path = REPO_ROOT) -> None:
        registry = json.loads((apps_dir / "teams.json").read_text())
        self.apps_dir = apps_dir
        self.org: str = registry["org"]
        self.repositories: list[str] = registry["repositories"]
        self.teams: dict[str, dict[str, str]] = registry["teams"]
        self.publish_hours: list[int] = list(registry.get("publish_hours_utc", []))
        live = repo_root / ".github" / "CODEOWNERS"
        source = live if live.is_file() else apps_dir / "CODEOWNERS"
        self.code_owners = CodeOwners.parse(source.read_text())

    def check(self, team: str) -> str:
        """Return the team's slug, or refuse a name that is not one of the teams."""
        if team not in self.teams:
            raise Refusal(f"'{team}' is not a team; the teams are: {', '.join(self.teams)}")
        return team

    def manifest(self, team: str) -> dict[str, Any]:
        """Return the App manifest registered for a team (`.github/apps/<team>.json`)."""
        return json.loads((self.apps_dir / f"{self.check(team)}.json").read_text())

    def team_of_login(self, login: str) -> str | None:
        """Return the team whose bot has this login, or None for anyone else."""
        for team in self.teams:
            if bot_login(team) == login:
                return team
        return None

    def owning_teams(self, path: str) -> set[str]:
        """Return the teams that own a path, from its CODEOWNERS line (`@org/<team>`)."""
        prefix = f"@{self.org}/"
        return {
            owner[len(prefix) :]
            for owner in self.code_owners.owners(path)
            if owner.startswith(prefix)
        }

    def required_reviewers(self, author: str | None, paths: Iterable[str]) -> set[str]:
        """Return the teams that must approve a change.

        Every team owning a changed path reviews it, except the author's own team; when that
        leaves no one (the author owns every path), the author's peer team reviews instead.

        Args:
            author: The authoring team, or None when a person or an outside bot opened it.
            paths: The changed paths.

        Returns:
            The team slugs whose bots must approve.
        """
        owners: set[str] = set()
        for path in paths:
            owners |= self.owning_teams(path)
        required = owners - {author} if author else owners
        if not required and author:
            required = {self.teams[author]["peer"]}
        return required


class MessageGuard:
    """What every commit message, title, body and branch name passes before a bot sends it.

    Two lists, both kept outside the repository and both required: the team bots' own
    (`team-bots/denylist.txt`: the names no bot writes) and the anonymity list beside it
    (`anonymity-denylist.txt`: personal names, hosts and paths). One entry per line; blank lines
    and `#` lines are skipped. An entry is a regular expression, matched case-insensitively as
    a whole word (no letter or digit just before or after it); one that does not compile is
    matched as literal text.
    """

    def __init__(self, lists: Sequence[Path] | None = None) -> None:
        folder = key_dir()
        self.lists = (
            list(lists)
            if lists is not None
            else [folder / DENYLIST_NAME, folder.parent / ANONYMITY_DENYLIST_NAME]
        )
        self.compiled: list[tuple[str, re.Pattern[str]]] | None = None

    @staticmethod
    def pattern(entry: str) -> re.Pattern[str]:
        """Return an entry as a whole-word, case-insensitive pattern."""
        try:
            re.compile(entry)
            body = entry
        except re.error:
            body = re.escape(entry)
        return re.compile(rf"(?<![A-Za-z0-9])(?:{body})(?![A-Za-z0-9])", re.IGNORECASE)

    def patterns(self) -> list[tuple[str, re.Pattern[str]]]:
        """Return (where, pattern) for every entry of every list, refusing a missing or empty list.

        `where` is the list's name and the entry's line number, never the entry itself, so a
        refusal does not copy a personal name into a terminal or a log.
        """
        if self.compiled is None:
            compiled: list[tuple[str, re.Pattern[str]]] = []
            for path in self.lists:
                try:
                    lines = path.read_text().splitlines()
                except OSError:
                    lines = []
                entries = [
                    (f"{path.name} line {number}", line.strip())
                    for number, line in enumerate(lines, 1)
                    if line.strip() and not line.lstrip().startswith("#")
                ]
                if not entries:
                    raise Refusal(
                        f"no denylist at {path}: the bots send nothing until it exists "
                        "(one entry per line; specs/DREAMFERENCE_ORGANISATION.md §5.4)"
                    )
                compiled.extend((where, self.pattern(entry)) for where, entry in entries)
            self.compiled = compiled
        return self.compiled

    def refuse_named(self, text: str, what: str = "the text") -> None:
        """Refuse when the text matches any entry, naming the list and line, not the entry."""
        for where, pattern in self.patterns():
            if pattern.search(text):
                raise Refusal(f"{what} matches {where}, which no bot writes; reword it")

    def clean(self, text: str) -> str:
        """Return the text without trailers, or refuse it when it matches a denylist entry.

        Args:
            text: A commit message, a title or a body.

        Returns:
            The text with every stripped line removed and trailing blank lines dropped.
        """
        kept = []
        for line in text.splitlines():
            if any(rule.search(line) for rule in STRIPPED_LINES):
                # Said on stderr, so whoever wrote the message sees what did not leave with it.
                print(f"💡 stripped: {line.strip()}", file=sys.stderr)
            else:
                kept.append(line)
        while kept and not kept[-1].strip():
            kept.pop()
        cleaned = "\n".join(kept)
        self.refuse_named(cleaned)
        return cleaned

    def name(self, name: str) -> str:
        """Return a branch name unchanged, or refuse one that matches a denylist entry."""
        self.refuse_named(name, f"the branch name '{name}'")
        return name


@dataclass(frozen=True)
class AppCredentials:
    """One team's App: its id, its slug and the private key's path."""

    app_id: int
    slug: str
    key_path: Path

    @staticmethod
    def private(path: Path) -> None:
        """Refuse a key or a folder that anyone but its owner can read."""
        if path.stat().st_mode & (stat.S_IRWXG | stat.S_IRWXO):
            raise Refusal(f"{path} can be read by others; run: chmod go= {path}")

    @classmethod
    def load(cls, team: str, directory: Path | None = None) -> "AppCredentials":
        """Read a team's App id, slug and key path, refusing loose permissions.

        Args:
            team: The team's slug.
            directory: The key folder (default: `key_dir()`).

        Returns:
            The credentials.
        """
        folder = directory or key_dir()
        record, key = folder / f"{team}.json", folder / f"{team}.pem"
        if not record.is_file() or not key.is_file():
            raise Refusal(
                f"no App for '{team}' on this machine; the owner registers it: as_team.py register {team}"
            )
        cls.private(folder)
        cls.private(key)
        data = json.loads(record.read_text())
        return cls(int(data["app_id"]), str(data["slug"]), key)

    @classmethod
    def store(
        cls, team: str, conversion: dict[str, Any], directory: Path | None = None
    ) -> "AppCredentials":
        """Write what the manifest flow returned: the key (0600) and the App's id and slug.

        Args:
            team: The team's slug.
            conversion: The response of `POST /app-manifests/{code}/conversions`.
            directory: The key folder (default: `key_dir()`).

        Returns:
            The stored credentials.
        """
        folder = directory or key_dir()
        folder.mkdir(parents=True, exist_ok=True, mode=0o700)
        folder.chmod(0o700)
        key = folder / f"{team}.pem"
        try:
            descriptor = os.open(key, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        except FileExistsError as exists:
            raise Refusal(
                f"{key} exists; delete the old App and its key before registering again"
            ) from exists
        with os.fdopen(descriptor, "w") as handle:
            handle.write(conversion["pem"])
        record = {"app_id": conversion["id"], "slug": conversion["slug"]}
        (folder / f"{team}.json").write_text(json.dumps(record, indent=2) + "\n")
        return cls(int(conversion["id"]), str(conversion["slug"]), key)


class JwtSigner:
    """Signs the App's JSON web token (RS256) with `openssl`, so no Python crypto package is needed."""

    def __init__(
        self,
        run: Callable[..., subprocess.CompletedProcess[bytes]] = subprocess.run,
        clock: Callable[[], float] = time.time,
    ) -> None:
        self.run = run
        self.clock = clock

    @staticmethod
    def b64url(data: bytes) -> str:
        """Return unpadded base64url, as JSON web tokens use it."""
        return base64.urlsafe_b64encode(data).rstrip(b"=").decode()

    def token(self, credentials: AppCredentials) -> str:
        """Return a JSON web token that authenticates as the App for nine minutes."""
        now = int(self.clock())
        header = {"alg": "RS256", "typ": "JWT"}
        claims = {
            "iat": now - JWT_BACKDATE_SECONDS,
            "exp": now + JWT_LIFETIME_SECONDS,
            "iss": str(credentials.app_id),
        }
        signing_input = (
            f"{self.b64url(json.dumps(header).encode())}.{self.b64url(json.dumps(claims).encode())}"
        )
        signed = self.run(
            ["openssl", "dgst", "-sha256", "-sign", str(credentials.key_path)],
            input=signing_input.encode(),
            capture_output=True,
            check=True,
        )
        return f"{signing_input}.{self.b64url(signed.stdout)}"


class GitHub:
    """GitHub's REST and GraphQL APIs as a team's App, through one injectable session."""

    def __init__(
        self,
        session: Any = None,
        signer: JwtSigner | None = None,
        key_directory: Path | None = None,
    ) -> None:
        self.session = session or requests.Session()
        self.signer = signer or JwtSigner()
        self.key_directory = key_directory
        self.tokens: dict[tuple[str, str], str] = {}

    def call(self, method: str, path: str, auth: str | None = None, body: Any = None) -> Any:
        """Send one request and return its JSON (None for an empty answer), refusing on an error.

        Args:
            method: The HTTP method.
            path: A path under the API (`/repos/...`) or a full URL.
            auth: A token for the Authorization header, or None.
            body: The JSON body, or None.

        Returns:
            The decoded JSON.
        """
        url = path if path.startswith("https://") else f"{API}{path}"
        headers = {
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": API_VERSION,
            "User-Agent": USER_AGENT,
        }
        if auth:
            headers["Authorization"] = f"Bearer {auth}"
        response = self.session.request(method, url, headers=headers, json=body, timeout=60)
        if response.status_code >= 400:
            try:
                message = response.json().get("message", "")
            except ValueError:
                message = response.text[:200]
            raise Refusal(f"GitHub answered {response.status_code} to {method} {path}: {message}")
        if response.status_code == 204 or not response.content:
            return None
        return response.json()

    def pages(self, path: str, auth: str) -> list[Any]:
        """Return every item of a paginated list (100 per page)."""
        items: list[Any] = []
        page = 1
        while True:
            separator = "&" if "?" in path else "?"
            batch = self.call("GET", f"{path}{separator}per_page=100&page={page}", auth)
            items.extend(batch)
            if len(batch) < 100:
                return items
            page += 1

    def installation_token(self, team: str, repo: str) -> str:
        """Return an installation token for the team's App on one repository (cached for the run)."""
        if (team, repo) not in self.tokens:
            credentials = AppCredentials.load(team, self.key_directory)
            app_jwt = self.signer.token(credentials)
            installation = self.call("GET", f"/repos/{repo}/installation", app_jwt)
            granted = self.call(
                "POST",
                f"/app/installations/{installation['id']}/access_tokens",
                app_jwt,
                {"repositories": [repo.split("/", 1)[1]]},
            )
            self.tokens[(team, repo)] = granted["token"]
        return self.tokens[(team, repo)]

    def identity(self, team: str) -> tuple[str, str]:
        """Return the bot's login and the commit email GitHub links to it.

        The email is `<user id>+<login>@users.noreply.github.com`, where the id is the bot user's
        (not the App's); it is looked up, never guessed.
        """
        login = bot_login(team)
        user = self.call("GET", f"/users/{urllib.parse.quote(login)}")
        return login, f"{user['id']}+{login}@users.noreply.github.com"

    def graphql(self, token: str, query: str, variables: dict[str, Any]) -> dict[str, Any]:
        """Run one GraphQL operation and return its data, refusing on any error."""
        answer = self.call("POST", "/graphql", token, {"query": query, "variables": variables})
        if answer.get("errors"):
            raise Refusal(
                f"GitHub refused the GraphQL call: {answer['errors'][0].get('message', '')}"
            )
        return answer["data"]


class Git:
    """The local repository the commits come from."""

    def __init__(self, cwd: Path) -> None:
        self.cwd = cwd

    def run(
        self, *args: str, env: dict[str, str] | None = None, stdin: bytes | None = None
    ) -> bytes:
        """Run git and return its output, refusing with git's message when it fails."""
        result = subprocess.run(
            ["git", *args],
            cwd=self.cwd,
            input=stdin,
            capture_output=True,
            env={**os.environ, **(env or {})},
        )
        if result.returncode != 0:
            raise Refusal(
                f"git {' '.join(args[:2])} failed: {result.stderr.decode(errors='replace').strip()}"
            )
        return result.stdout

    def text(self, *args: str) -> str:
        """Run git and return its output as stripped text."""
        return self.run(*args).decode().strip()

    def commits(self, base: str, head: str) -> list[str]:
        """Return the commits of base..head, oldest first, refusing merges and an empty range."""
        listed = self.text("rev-list", "--reverse", "--parents", f"{base}..{head}").splitlines()
        if not listed:
            raise Refusal(f"nothing to publish: {base}..{head} is empty")
        commits = []
        for line in listed:
            sha, *parents = line.split()
            if len(parents) != 1:
                raise Refusal(
                    f"{sha[:12]} is a merge; publish a linear series (rebase it onto {base})"
                )
            commits.append(sha)
        return commits

    def changes(self, commit: str) -> tuple[list[dict[str, str]], list[dict[str, str]]]:
        """Return a commit's file additions (base64) and deletions, refusing what GitHub cannot take.

        createCommitOnBranch writes plain files only, so a symlink, a submodule, an executable or
        a mode change has to go through `--via git`.
        """
        raw = self.run(
            "diff-tree", "-r", "--no-renames", "--no-commit-id", "-z", "--raw", f"{commit}^", commit
        )
        fields = raw.decode().split("\0")
        additions: list[dict[str, str]] = []
        deletions: list[dict[str, str]] = []
        index = 0
        while index + 1 < len(fields) and fields[index]:
            old_mode, new_mode, _old_sha, new_sha, status = fields[index].lstrip(":").split()
            path = fields[index + 1]
            index += 2
            if status.startswith("D"):
                deletions.append({"path": path})
                continue
            if new_mode != PLAIN_FILE_MODE or old_mode not in (PLAIN_FILE_MODE, ABSENT_MODE):
                raise Refusal(
                    f"{commit[:12]} changes {path} (mode {old_mode} -> {new_mode}), which GitHub's commit API "
                    "cannot write; publish this series with --via git"
                )
            contents = self.run("cat-file", "blob", new_sha)
            additions.append({"path": path, "contents": base64.b64encode(contents).decode()})
        return additions, deletions


