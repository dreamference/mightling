class RegistrationSite:
    """The phone's page: one Create button per team, and the callback GitHub sends the phone to.

    It answers only under a random path token and only to the two names the node has: its
    mDNS name and its current LAN address (both read at start, never stored). GitHub's
    `redirect_url` is built from the name the phone used to open the page, so a phone that
    cannot resolve `.local` names opens the address instead and comes back the same way.
    """

    def __init__(
        self,
        registration: ManifestRegistration,
        teams: Sequence[str],
        names: Sequence[str],
        token: str,
        directory: Path | None = None,
    ) -> None:
        self.registration = registration
        self.teams = list(teams)
        self.names = list(names)
        self.token = token
        self.directory = directory
        self.states: dict[str, str] = {}
        self.done: dict[str, AppCredentials] = {}
        self.problem = ""
        for team in self.teams:
            try:
                self.done[team] = AppCredentials.load(team, directory)
            except Refusal:
                continue

    @property
    def finished(self) -> bool:
        """Return whether every listed team has its App."""
        return all(team in self.done for team in self.teams)

    def state_for(self, team: str) -> str:
        """Return the one live state for a team: `<team>.<random>`, good for one callback."""
        for state, owner in self.states.items():
            if owner == team:
                return state
        state = f"{team}.{secrets.token_urlsafe(18)}"
        self.states[state] = team
        return state

    def page(self, name: str) -> str:
        """Return the page, its forms sending GitHub back to the name the phone used."""
        base = f"http://{name}/{self.token}"
        org = html.escape(self.registration.registry.org)
        rows = []
        for team in self.teams:
            title = html.escape(self.registration.registry.teams[team]["name"])
            if team in self.done:
                slug = self.done[team].slug
                install = f"{WEB}/apps/{urllib.parse.quote(slug)}/installations/new"
                action = (
                    f'<span class="ok">✅ app {self.done[team].app_id}</span> '
                    f'<a href="{html.escape(install)}">Install</a>'
                )
            else:
                action = self.registration.form(team, f"{base}/callback", self.state_for(team))
            rows.append(
                f"<li><span><b>{title}</b><small>dreamference-{html.escape(team)}</small></span>{action}</li>"
            )
        addresses = " or ".join(
            f"<code>http://{html.escape(other)}/{self.token}/</code>" for other in self.names
        )
        problem = f'<p class="note">❌ {html.escape(self.problem)}</p>' if self.problem else ""
        closing = (
            "<p class=ok>All listed teams have their App. This page has stopped.</p>"
            if self.finished
            else ""
        )
        return (
            "<!doctype html><html lang=en><meta charset=utf-8>"
            '<meta name="viewport" content="width=device-width,initial-scale=1">'
            f"<title>Team bots</title><style>{PAGE_STYLE}</style><main>"
            f"<h1>Register the team bots</h1>{problem}{closing}"
            f"<p>Sign in to GitHub on this phone as an owner of <b>{org}</b>. Tap <b>Create</b>, "
            f"then <b>Create GitHub App for {org}</b> on GitHub; it comes back here. Then tap "
            "<b>Install</b>: choose <b>Only select repositories</b>, <b>mightling</b> and "
            "<b>ling-engine</b>.</p>"
            f"<ul>{''.join(rows)}</ul>"
            f'<p class="note">This page answers at {addresses} while the command runs, '
            "for an hour at most. Open it by the second address if the first does not load.</p>"
            "</main></html>"
        )

    def handle(self, path: str, host: str) -> tuple[int, dict[str, str], str]:
        """Answer one GET: (status, headers, body). Anything but the token's two paths is 404.

        Args:
            path: The request's path and query.
            host: The Host header the phone sent.

        Returns:
            The response.
        """
        url = urllib.parse.urlparse(path)
        if host not in self.names:
            return 404, {}, "not found"
        if url.path == f"/{self.token}/":
            return 200, {}, self.page(host)
        if url.path != f"/{self.token}/callback":
            return 404, {}, "not found"
        query = urllib.parse.parse_qs(url.query)
        state = (query.get("state") or [""])[0]
        code = (query.get("code") or [""])[0]
        team = self.states.pop(state, None)
        if team is None or not code:
            self.problem = "That link is spent or not from this page; tap Create again."
            return 303, {"Location": f"/{self.token}/"}, ""
        try:
            self.done[team] = self.registration.convert(team, code, self.directory)
            self.problem = ""
            print(f"✅ dreamference-{team} is app {self.done[team].app_id}")
        except Refusal as refused:
            self.problem = str(refused)
        return 303, {"Location": f"/{self.token}/"}, ""


def lan_address() -> str:
    """Return the address this machine uses on its LAN, read now and never stored.

    Connecting a UDP socket sends nothing; it only makes the kernel pick the route's source
    address. 192.0.2.1 is a documentation address (RFC 5737), never a real peer.
    """
    probe = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        probe.connect(("192.0.2.1", 9))
        return str(probe.getsockname()[0])
    finally:
        probe.close()


def serve_registration(
    site_for: Callable[[int], RegistrationSite], address: str
) -> RegistrationSite:
    """Serve the phone's page on the LAN address, on a free port, until done or an hour passes.

    Args:
        site_for: Builds the site once the port is known.
        address: The LAN address to bind (never every interface).

    Returns:
        The site, with what was registered.
    """
    holder: dict[str, RegistrationSite] = {}

    class Handler(http.server.BaseHTTPRequestHandler):
        def log_message(self, format: str, *args: object) -> None:  # noqa: A002 - BaseHTTPRequestHandler's name
            return

        def do_GET(self) -> None:  # BaseHTTPRequestHandler's name
            site = holder["site"]
            status, headers, body = site.handle(self.path, self.headers.get("Host", ""))
            encoded = body.encode()
            self.send_response(status)
            for key, value in {
                "Content-Type": "text/html; charset=utf-8",
                "Cache-Control": "no-store",
                "Referrer-Policy": "no-referrer",
                **headers,
            }.items():
                self.send_header(key, value)
            self.send_header("Content-Length", str(len(encoded)))
            self.end_headers()
            self.wfile.write(encoded)
            if site.finished and status == HTTP_OK:
                # The last team's page has been shown; the token dies with the server.
                threading.Thread(target=self.server.shutdown, daemon=True).start()

    server = http.server.ThreadingHTTPServer((address, 0), Handler)
    site = holder["site"] = site_for(server.server_port)
    for name in site.names:
        print(f"🚀 http://{name}/{site.token}/")
    print(
        "💡 Open the first link on the phone (the second if the first does not load); Ctrl-C stops."
    )
    timer = threading.Timer(REGISTER_TIMEOUT_SECONDS, server.shutdown)
    timer.start()
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("⚠️ stopped")
    finally:
        timer.cancel()
        server.server_close()
    return site


