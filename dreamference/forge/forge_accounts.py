"""The forge's accounts (specs/DREAMFERENCE_MIGHTLING_FORGEJO.md §2.2).

- `forge-admin`, created first, an administrator used only by `ling-admin` (through an access
  token kept 0600 on the node); never shown in a UI.
- `owner`, the node owner's account, not an administrator, with a generated 24-character password
  shown once at the end of the install and kept 0600 so `forge password --show` prints it again
  on the node's own terminal.
- `mirror` on the forge of record only: a plain account whose read token the mirror nodes pull
  with. It sees what any signed-in account sees, so a private repository never reaches a mirror.

Forgejo generates the passwords (`--random-password`), so none is ever on a command line; they are
read back from its output and never printed by anything but `show_password_once`.
"""

import re
import sys
from http import HTTPStatus
from typing import Final

from dreamference.forge.forge_container import ForgeContainer
from dreamference.forge.forge_settings import (
    ADMIN,
    MIRROR_ACCOUNT,
    OWNER,
    PASSWORD_LENGTH,
    ForgeSettings,
)

GENERATED: Final[re.Pattern] = re.compile(r"generated random password is '([^']+)'")
EMAIL_DOMAIN: Final[str] = "forge.invalid"
# What `generate-access-token --raw` prints: a token of 40 hex digits.
TOKEN_PATTERN: Final[str] = r"[0-9a-f]{40}"


class ForgeAccounts:
    """Creates the accounts and their tokens, once."""

    @classmethod
    def create_user(cls, username: str, admin: bool) -> str | None:
        """Create an account with a generated password.

        Args:
            username: The account's name.
            admin: Whether it is an administrator.

        Returns:
            str | None: The generated password, or None when the account could not be created.
        """
        arguments = [
            "admin",
            "user",
            "create",
            "--username",
            username,
            "--email",
            f"{username}@{EMAIL_DOMAIN}",
            "--random-password",
            "--random-password-length",
            str(PASSWORD_LENGTH),
            "--must-change-password=false",
        ]
        if admin:
            arguments.append("--admin")
        result = ForgeContainer.forgejo(arguments, timeout=120)
        match = GENERATED.search(result.stdout or "")
        if result.returncode != 0 or not match:
            return None
        return match.group(1)

    @classmethod
    def generate_token(cls, username: str, name: str, scopes: str) -> str | None:
        """Generate an access token for an account.

        Args:
            username: The account.
            name: The token's name (unique per account).
            scopes: Forgejo's scope list (`all`, `read:repository`, …).

        Returns:
            str | None: The token, or None when it could not be made.
        """
        result = ForgeContainer.forgejo(
            [
                "admin",
                "user",
                "generate-access-token",
                "--username",
                username,
                "--token-name",
                name,
                "--scopes",
                scopes,
                "--raw",
            ],
            timeout=120,
        )
        token = (result.stdout or "").strip().splitlines()[-1:] if result.returncode == 0 else []
        return token[0].strip() if token and re.fullmatch(TOKEN_PATTERN, token[0].strip()) else None

    @classmethod
    def admin_token(cls) -> str | None:
        """Return `forge-admin`'s token.

        Returns:
            str | None: `forge-admin`'s token, or None before the setup made it.
        """
        return ForgeSettings.read_secret("admin-token")

    @classmethod
    def ensure(cls) -> tuple[bool, str | None]:
        """Create `forge-admin` and its token, then `owner`, when they do not exist yet.

        Returns:
            tuple[bool, str | None]: Whether both exist now, and the owner's password when it
            was generated by this call (to be shown once), else None.
        """
        if not cls.admin_token():
            if not ForgeSettings.read_secret("admin-password"):
                password = cls.create_user(ADMIN, admin=True)
                if password is None:
                    print(
                        f"❌ Could not create the forge's `{ADMIN}` account; "
                        f"`docker logs {ForgeContainer.name}` says why."
                    )
                    return False, None
                ForgeSettings.write_secret("admin-password", password)
            token = cls.generate_token(ADMIN, "ling-admin", "all")
            if token is None:
                print(f"❌ Could not make `{ADMIN}`'s access token.")
                return False, None
            ForgeSettings.write_secret("admin-token", token)
        if ForgeSettings.read_secret("owner-password"):
            return True, None
        password = cls.create_user(OWNER, admin=False)
        if password is None:
            print(f"❌ Could not create the forge's `{OWNER}` account.")
            return False, None
        ForgeSettings.write_secret("owner-password", password)
        return True, password

    @classmethod
    def owner_is_admin(cls) -> bool | None:
        """Tell whether `owner` is an administrator.

        Returns:
            bool | None: Whether `owner` is an administrator (it must not be), or None when
            the API could not say.
        """
        status, body = ForgeContainer.api("GET", f"/users/{OWNER}", cls.admin_token())
        if status != HTTPStatus.OK or not isinstance(body, dict):
            return None
        return bool(body.get("is_admin"))

    @classmethod
    def show_password_once(cls, password: str) -> None:
        """Print the owner's new password on a terminal, or where it is kept anywhere else.

        In a log or a pipe the password itself is never printed.

        Args:
            password: The password just generated.
        """
        where = ForgeSettings.secret_path("owner-password")
        if sys.stdout.isatty():
            print(
                f"🔑 The forge's `{OWNER}` password, shown this once: {password}\n"
                f"   It is kept at {where} (0600); `ling-admin forge password --show` prints it again here."
            )
        else:
            print(
                f"🔑 The forge's `{OWNER}` account has a generated password, kept at {where} (0600).\n"
                "   Not printed here because this is not a terminal: `ling-admin forge password --show` prints it."
            )

    @classmethod
    def mirror_token(cls) -> str | None:
        """Return the read token mirror nodes pull with, made once on the forge of record.

        Returns:
            str | None: The token, or None when it could not be made.
        """
        token = ForgeSettings.read_secret("mirror-token")
        if token:
            return token
        status, _ = ForgeContainer.api("GET", f"/users/{MIRROR_ACCOUNT}", cls.admin_token())
        if status == HTTPStatus.NOT_FOUND and cls.create_user(MIRROR_ACCOUNT, admin=False) is None:
            return None
        token = cls.generate_token(MIRROR_ACCOUNT, "mirrors", "read:repository")
        if token:
            ForgeSettings.write_secret("mirror-token", token)
        return token

    @classmethod
    def add_key(cls, key_text: str, title: str = "ling-admin") -> bool:
        """Add an SSH public key to `owner`.

        Args:
            key_text: The public key's line.
            title: Its title in the forge.

        Returns:
            bool: Whether the forge took it.
        """
        status, body = ForgeContainer.api(
            "POST",
            f"/admin/users/{OWNER}/keys",
            cls.admin_token(),
            {"key": key_text.strip(), "title": title, "read_only": False},
        )
        if status != HTTPStatus.CREATED:
            message = body.get("message") if isinstance(body, dict) else body
            print(f"❌ The forge refused the key (HTTP {status}): {message}")
            return False
        return True
